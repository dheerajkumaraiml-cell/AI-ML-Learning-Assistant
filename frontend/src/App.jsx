import React, { useState } from "react";
import Sidebar from "./components/Sidebar.jsx";
import ChatWindow from "./components/ChatWindow.jsx";
import LearningPanel from "./components/LearningPanel.jsx";

const suggestedTopics = [
  "What is machine learning?",
  "Explain neural networks",
  "How does self-attention work?",
  "What is a Transformer?",
];

function createDemoResponse(question) {
  const text = question.toLowerCase();

  if (text.includes("attention")) {
    return `Self-attention helps a Transformer understand how tokens relate to one another.

It creates three representations:
- Query (Q): what a token is looking for.
- Key (K): what information a token offers for matching.
- Value (V): the information that gets combined.

The attention calculation is softmax(QKᵀ / √dₖ)V.

In our project, attention helps the fine-tuned language model use context when generating explanations.

This is a demo response, not yet generated by your trained model.`;
  }

  if (text.includes("transformer")) {
    return `A Transformer is a neural network architecture that uses attention to process sequences.

Its main components include:
1. Token embeddings
2. Positional information
3. Self-attention
4. Feed-forward networks
5. Residual connections and layer normalization

A causal language model uses a causal mask so it cannot attend to future tokens when predicting the next token.

Our project fine-tunes a Qwen Transformer model.`;
  }

  if (text.includes("neural network")) {
    return `A neural network learns patterns by applying trainable weights and biases to input data.

During training:
1. The model makes predictions.
2. A loss function measures prediction errors.
3. Backpropagation calculates gradients.
4. An optimizer updates model parameters.

This process repeats over batches and epochs to improve the model's predictions.`;
  }

  if (text.includes("machine learning")) {
    return `Machine learning is a field of AI where models learn patterns from data instead of relying only on explicitly written rules.

A typical workflow is:
1. Collect and clean data.
2. Tokenize or transform the data.
3. Split it into training, validation, and test sets.
4. Train the model.
5. Evaluate its performance.
6. Save the model and use it for inference.

Our AI/ML Learning Assistant follows this workflow and adds a FastAPI backend for serving predictions.`;
  }

  return `Let's understand your question step by step.

First, identify the concept and why it is needed. Next, examine its inputs, outputs, and internal process. Finally, connect it to our AI/ML Learning Assistant project and consider how we would implement and test it.

For now, this is a frontend demo response. We will connect the chat to your fine-tuned Qwen model through FastAPI in the next integration step.`;
}

export default function App() {
  const [activeSection, setActiveSection] = useState("chat");
  const [messages, setMessages] = useState([
    {
      id: 1,
      role: "assistant",
      content:
        "Hello! 👋 I'm your AI/ML Learning Assistant.\n\nAsk me about machine learning, NLP, Transformers, PyTorch, training, evaluation, or the engineering behind this project.\n\nWhat would you like to learn today?",
    },
  ]);
  const [isTyping, setIsTyping] = useState(false);

  function sendMessage(text) {
    const question = text.trim();

    if (!question || isTyping) return;

    const userMessage = {
      id: Date.now(),
      role: "user",
      content: question,
    };

    setMessages((current) => [...current, userMessage]);
    setIsTyping(true);

    // Temporary demo behavior.
    // Replace this with a request to the FastAPI inference endpoint.
    window.setTimeout(() => {
      const assistantMessage = {
        id: Date.now() + 1,
        role: "assistant",
        content: createDemoResponse(question),
      };

      setMessages((current) => [...current, assistantMessage]);
      setIsTyping(false);
    }, 500);
  }

  function startNewChat() {
    setMessages([
      {
        id: Date.now(),
        role: "assistant",
        content:
          "New conversation started! What AI/ML concept would you like to explore?",
      },
    ]);
    setActiveSection("chat");
    setIsTyping(false);
  }

  function renderSection() {
    if (activeSection === "topics") {
      return (
        <section className="section-placeholder">
          <h2>Learning Topics 📚</h2>
          <p>Choose a topic to explore with your learning assistant.</p>

          {suggestedTopics.map((topic) => (
            <button
              key={topic}
              type="button"
              onClick={() => {
                setActiveSection("chat");
                sendMessage(topic);
              }}
            >
              {topic}
            </button>
          ))}
        </section>
      );
    }

    if (activeSection === "progress") {
      const questionCount = messages.filter(
        (message) => message.role === "user"
      ).length;

      return (
        <section className="section-placeholder">
          <h2>My Learning Progress 📈</h2>
          <p>Questions in this conversation: {questionCount}</p>
          <p>
            Suggested next goals: tokenization, embeddings, attention,
            training, and model evaluation.
          </p>
          <p>
            This is session-only information; progress is not saved to a
            database yet.
          </p>
        </section>
      );
    }

    if (activeSection === "settings") {
      return (
        <section className="section-placeholder">
          <h2>Settings ⚙️</h2>
          <p>
            The frontend is currently running in demo mode. Backend
            connection and authentication will be configured during
            integration.
          </p>
          <p>
            API keys must be verified by the backend and must not be
            hardcoded into frontend source code.
          </p>
          <button type="button" onClick={startNewChat}>
            Start a new chat
          </button>
        </section>
      );
    }

    return (
      <ChatWindow
        messages={messages}
        onSend={sendMessage}
        isTyping={isTyping}
      />
    );
  }

  return (
    <div className="app">
      <header className="app-header">
        <div className="brand">
          <div className="brand-icon" aria-hidden="true">
            🧠
          </div>

          <div>
            <h1>AI/ML Learning Assistant</h1>
            <p>Your personal AI and machine learning tutor</p>
          </div>
        </div>

        <div className="connection-status">
          <span className="status-dot" />
          <span>Frontend demo</span>
        </div>
      </header>

      <div className="app-layout">
        <Sidebar
          activeSection={activeSection}
          onNavigate={setActiveSection}
        />

        <main className="main-content">{renderSection()}</main>

        <LearningPanel
          onSelectTopic={(topic) => {
            if (isTyping) return;
            setActiveSection("chat");
            sendMessage(topic);
          }}
          onNewChat={startNewChat}
          questionCount={
            messages.filter((message) => message.role === "user").length
          }
        />
      </div>
    </div>
  );
}
